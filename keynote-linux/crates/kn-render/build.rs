// Tests that read the private test files (Apple-made samples and the Mac research, kept on the
// developer's computer and never published) run only where those files are; elsewhere they are
// reported as ignored.
//
// Also generates a compact compile-time index of the metric-matched Apple stand-in fonts
// (`matched_index.rs`) so WebAssembly builds can fetch only the faces a document actually uses
// over HTTP instead of embedding all ~62 MB into the .wasm binary.
use std::fmt::Write as _;
use std::path::PathBuf;

const MATCH_NAME_ID: u16 = 32000;

fn main() {
    println!("cargo::rustc-check-cfg=cfg(private_testdata)");
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let probe = dir.join("../../testdata");
    println!("cargo::rerun-if-changed={}", probe.display());
    if probe.exists() {
        println!("cargo::rustc-cfg=private_testdata");
    }

    generate_matched_index(&dir);
}

fn norm_key(s: &str) -> String {
    s.trim_start_matches('.').to_ascii_lowercase().replace([' ', '-', '_'], "")
}

fn stand_in_family(family: &str) -> String {
    let k = norm_key(family);
    match k.as_str() {
        "sfpro" | "sfns" | "sfnstext" | "systemfont" | "applesystemuifont" | "sfui" | "sfuitext" => "sfprotext".into(),
        "sfnsdisplay" | "sfuidisplay" => "sfprodisplay".into(),
        "newyork" => "newyorksmall".into(),
        _ => k,
    }
}

fn be16(data: &[u8], o: usize) -> Option<u16> {
    data.get(o..o + 2).map(|b| u16::from_be_bytes([b[0], b[1]]))
}

fn be32(data: &[u8], o: usize) -> Option<u32> {
    data.get(o..o + 4).map(|b| u32::from_be_bytes([b[0], b[1], b[2], b[3]]))
}

fn table_offset(data: &[u8], tag: &[u8; 4]) -> Option<usize> {
    let dir = if data.get(0..4) == Some(b"ttcf") { be32(data, 12)? as usize } else { 0 };
    let n = be16(data, dir + 4)? as usize;
    (0..n).find_map(|i| {
        let rec = dir + 12 + 16 * i;
        (data.get(rec..rec + 4)? == tag).then(|| be32(data, rec + 8).map(|o| o as usize)).flatten()
    })
}

fn parse_ttf_meta(data: &[u8]) -> Option<(String, String, u16, bool)> {
    let name = table_offset(data, b"name")?;
    let (count, strings) = (be16(data, name + 2)? as usize, name + be16(data, name + 4)? as usize);
    let record = (0..count).find_map(|i| {
        let r = name + 6 + 12 * i;
        let (platform, id) = (be16(data, r)?, be16(data, r + 6)?);
        if id != MATCH_NAME_ID {
            return None;
        }
        let (len, off) = (be16(data, r + 8)? as usize, be16(data, r + 10)? as usize);
        let bytes = data.get(strings + off..strings + off + len)?;
        Some(if platform == 3 || platform == 0 {
            String::from_utf16_lossy(&bytes.chunks_exact(2).map(|c| u16::from_be_bytes([c[0], c[1]])).collect::<Vec<_>>())
        } else {
            bytes.iter().map(|&b| b as char).collect()
        })
    })?;
    let (orig_fam, orig_ps) = record.split_once('|')?;
    let (weight, os2_italic) = table_offset(data, b"OS/2")
        .map(|o| (be16(data, o + 4).unwrap_or(400), be16(data, o + 62).is_some_and(|f| f & 1 != 0)))
        .unwrap_or((400, false));
    let head_italic = table_offset(data, b"head").and_then(|h| be16(data, h + 44)).is_some_and(|m| m & 2 != 0);
    Some((orig_fam.to_string(), orig_ps.to_string(), weight, os2_italic || head_italic))
}

fn generate_matched_index(manifest_dir: &std::path::Path) {
    let src_path = manifest_dir.join("src/fonts_matched.rs");
    println!("cargo::rerun-if-changed={}", src_path.display());
    let src = std::fs::read_to_string(&src_path).expect("read src/fonts_matched.rs");
    let mut out = String::from(
        "// Generated by kn-render/build.rs: index of fonts/matched/*.ttf for lazy WASM fetching.\n\
         #[allow(dead_code)]\n\
         #[derive(Debug, Clone, Copy)]\n\
         pub(crate) struct MatchedEntry {\n\
         \x20   pub family: &'static str,\n\
         \x20   pub ps: &'static str,\n\
         \x20   pub style: &'static str,\n\
         \x20   pub weight: u16,\n\
         \x20   pub italic: bool,\n\
         \x20   pub rel_path: &'static str,\n\
         }\n\n\
         #[allow(dead_code)]\n\
         pub(crate) const MATCHED_INDEX: &[MatchedEntry] = &[\n",
    );
    let prefix = "include_bytes!(\"../fonts/matched/";
    for line in src.lines() {
        let Some(start) = line.find(prefix) else { continue };
        let rest = &line[start + prefix.len()..];
        let Some(end) = rest.find('"') else { continue };
        let rel_path = &rest[..end];
        let full = manifest_dir.join("fonts/matched").join(rel_path);
        let Ok(bytes) = std::fs::read(&full) else { continue };
        let Some((orig_fam, orig_ps, weight, italic)) = parse_ttf_meta(&bytes) else { continue };
        let fam_k = stand_in_family(&orig_fam);
        let ps_k = norm_key(&orig_ps);
        let style_k = norm_key(orig_ps.split_once('-').map_or("", |s| s.1));
        let _ = writeln!(
            out,
            "    MatchedEntry {{ family: {fam_k:?}, ps: {ps_k:?}, style: {style_k:?}, weight: {weight}, italic: {italic}, rel_path: {rel_path:?} }},"
        );
    }
    out.push_str("];\n");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out_dir.join("matched_index.rs"), out).expect("write matched_index.rs");
}

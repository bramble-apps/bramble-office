#!/usr/bin/env python3
"""Builds the suite's icon font, BrambleIcons.ttf, from two MIT-licensed icon libraries:
Phosphor (regular and fill weights) and Tabler (outline), with Tabler's strokes drawn at
Phosphor's line weight (1.5 px on its 24 px grid) so the two read as one family.

    make_icon_font.py <phosphor package dir> <tabler package dir>

(the npm packages @phosphor-icons/core and @tabler/icons, unpacked). Writes
crates/lg-app/data/icons/BrambleIcons.ttf, the two licences beside it, and
crates/lg-app/src/glyphs_gen.rs (a constant per icon: crate::glyphs::ph::PIANO_KEYS, …).
Needs fonttools and picosvg (skia-pathops comes with it)."""
import os, re, sys
import pathops
from picosvg.svg import SVG
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'crates/lg-app/data/icons')
UPM, ASC, DESC = 1024, 896, -128
BASE = 0xF0000  # Supplementary Private Use Area-A
TABLER_STROKE = '1.5'


def outline(svg_text, viewbox):
    """The icon's filled outline as one pathops Path, in the icon's own units."""
    pico = SVG.fromstring(svg_text).topicosvg()
    total = pathops.Path()
    for shape in pico.shapes():
        if getattr(shape, 'fill', 'black') == 'none':
            continue
        p = pathops.Path()
        parse_path(shape.as_path().d, p.getPen())
        if getattr(shape, 'fill_rule', 'nonzero') == 'evenodd':
            p.fillType = pathops.FillType.EVEN_ODD
        p.simplify(fix_winding=True)
        total = pathops.op(total, p, pathops.PathOp.UNION, fix_winding=True)
    return total


def glyph(path, viewbox):
    x0, y0, w, h = viewbox
    s = UPM / max(w, h)
    pen = TTGlyphPen(None)
    # SVG is y-down from the top; the font is y-up from the baseline (the em box: DESC..ASC)
    tp = TransformPen(Cu2QuPen(pen, max_err=1.0, reverse_direction=True), (s, 0, 0, -s, -x0 * s, ASC + y0 * s))
    path.draw(tp)
    return pen.glyph()


def viewbox_of(text):
    m = re.search(r'viewBox="([-\d.\s]+)"', text)
    return tuple(float(v) for v in m.group(1).split())


def const_name(name):
    n = re.sub(r'[^A-Za-z0-9]+', '_', name).upper().strip('_')
    return 'N_' + n if n[:1].isdigit() else n


def main(ph_dir, tb_dir):
    sets = [
        ('ph', os.path.join(ph_dir, 'assets/regular'), lambda f: f[:-4]),
        ('ph_fill', os.path.join(ph_dir, 'assets/fill'), lambda f: f[:-4].removesuffix('-fill')),
        ('tb', os.path.join(tb_dir, 'icons/outline'), lambda f: f[:-4]),
    ]
    order, glyphs, cmap, consts = ['.notdef'], {}, {}, {}
    empty = TTGlyphPen(None)
    glyphs['.notdef'] = empty.glyph()
    cp = BASE
    for prefix, d, name_of in sets:
        consts[prefix] = []
        for f in sorted(os.listdir(d)):
            if not f.endswith('.svg'):
                continue
            text = open(os.path.join(d, f)).read()
            if prefix == 'tb':
                text = text.replace('stroke-width="2"', f'stroke-width="{TABLER_STROKE}"')
            try:
                g = glyph(outline(text, viewbox_of(text)), viewbox_of(text))
            except Exception as e:  # (an icon picosvg can't read: left out, said so)
                print(f'skipped {prefix}/{f}: {e}', file=sys.stderr)
                continue
            gname = f'{prefix}.{f[:-4]}'
            order.append(gname)
            glyphs[gname] = g
            cmap[cp] = gname
            consts[prefix].append((const_name(name_of(f)), name_of(f), cp))
            cp += 1
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({n: (UPM if n != '.notdef' else UPM, 0) for n in order})
    fb.setupHorizontalHeader(ascent=ASC, descent=DESC)
    fb.setupNameTable({'familyName': 'Bramble Icons', 'styleName': 'Regular',
                       'copyright': 'Phosphor Icons (MIT) and Tabler Icons (MIT); see the licences beside this file'})
    fb.setupOS2(sTypoAscender=ASC, sTypoDescender=DESC, usWinAscent=ASC, usWinDescent=-DESC)
    fb.setupPost()
    os.makedirs(OUT, exist_ok=True)
    fb.save(os.path.join(OUT, 'BrambleIcons.ttf'))
    rs = ['// Generated by tool/make_icon_font.py: do not edit.',
          '// One constant per icon of BrambleIcons.ttf (Phosphor regular `ph`, Phosphor fill `ph_fill`,',
          "// Tabler outline `tb`), each the icon's character as a &str.", '']
    for prefix, items in consts.items():
        rs.append(f'pub mod {prefix} {{')
        seen = set()
        for c, name, code in items:
            while c in seen:
                c += '_'
            seen.add(c)
            rs.append(f'    pub const {c}: &str = "\\u{{{code:X}}}";')
        rs.append('    /// Every icon: (its library name, its character).')
        rs.append('    pub const ALL: &[(&str, &str)] = &[' + ', '.join(f'("{n}", "\\u{{{code:X}}}")' for _, n, code in items) + '];')
        rs.append('}')
        rs.append('')
    open(os.path.join(ROOT, 'crates/lg-app/src/glyphs_gen.rs'), 'w').write('\n'.join(rs))
    for lib, d in (('phosphor', ph_dir), ('tabler', tb_dir)):
        open(os.path.join(OUT, f'LICENSE-{lib}.txt'), 'w').write(open(os.path.join(d, 'LICENSE')).read())
    print(f'{len(order) - 1} icons')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
